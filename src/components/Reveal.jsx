import { motion } from 'framer-motion'

// Fade-and-rise on scroll into view. Reused across sections for consistent,
// lightweight entrance animations. Respects prefers-reduced-motion via CSS.
export default function Reveal({ children, delay = 0, y = 24, className = '' }) {
  return (
    <motion.div
      className={className}
      initial={{ opacity: 0, y }}
      whileInView={{ opacity: 1, y: 0 }}
      viewport={{ once: true, amount: 0.2 }}
      transition={{ duration: 0.6, delay, ease: [0.22, 1, 0.36, 1] }}
    >
      {children}
    </motion.div>
  )
}
